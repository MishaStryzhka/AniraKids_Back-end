// Fresh loopback-only database. Never reads .env or accepts an external database URI.
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const { mkdtempSync, rmSync, readFileSync } = require('node:fs');
const { tmpdir } = require('node:os');
const path = require('node:path');
const net = require('node:net');
const vm = require('node:vm');
const mongoose = require('mongoose');
const User = require('../models/user');
const favorites = require('../controllers/auth/storefrontFavorites');
const { ProductV2Model: Product } = require('../build/v2/models');
const { publicCatalogueService } = require('../build/v2/services/public-catalogue.service');
const { parseCatalogueQuery } = require('../build/v2/routes/catalogue.routes');
process.env.SECRET_KEY = 'isolated-favorites-test-secret';
const authenticate = require('../middlewares/authenticate');
const jwt = require('jsonwebtoken');
const express = require('express');
let server;
assert.equal(process.env.NODE_ENV, 'test');
assert.equal(process.env.PUBLIC_BOOKING_TEST_ALLOW, '1');
mongoose.set('strictQuery', true);
let child, directory;
const watchdog = setTimeout(() => { child?.kill('SIGKILL'); process.exit(1); }, 60000);
watchdog.unref();
(async () => {
  const socket = net.createServer();
  await new Promise(resolve => socket.listen(0, '127.0.0.1', resolve));
  const port = socket.address().port;
  await new Promise(resolve => socket.close(resolve));
  directory = mkdtempSync(path.join(tmpdir(), 'anirakids-seznam-registration-'));
  child = spawn(process.env.PUBLIC_BOOKING_MONGOD_BINARY || 'mongod', ['--bind_ip', '127.0.0.1', '--port', String(port), '--dbpath', directory, '--nounixsocket'], { stdio: ['ignore', 'pipe', 'pipe'] });
  await new Promise((resolve, reject) => {
    let output = '';
    child.stdout.on('data', data => { output += data; if (output.includes('Waiting for connections')) resolve(); });
    child.stderr.on('data', () => {});
    child.once('error', reject); child.once('exit', code => reject(new Error('Owned Mongo exited: ' + code)));
  });
  await mongoose.connect(`mongodb://127.0.0.1:${port}/seznam_fixture`);
  await User.init();
  const userA = await User.create({ email: 'one@seznam.cz', provider: 'seznam' });
  const userB = await User.create({ email: 'two@seznam.cz', provider: 'seznam' });
  const tokenA = jwt.sign({ id: userA.id }, process.env.SECRET_KEY);
  const tokenB = jwt.sign({ id: userB.id }, process.env.SECRET_KEY);
  await User.updateOne({ _id: userA._id }, { $set: { tokens: [{ token: tokenA, device: {} }] } });
  await User.updateOne({ _id: userB._id }, { $set: { tokens: [{ token: tokenB, device: {} }] } });
  const productIds = [new mongoose.Types.ObjectId(), new mongoose.Types.ObjectId(), new mongoose.Types.ObjectId()];
  await Product.collection.insertMany(productIds.map((_id, i) => ({ _id, slug: 'favorite-' + i, name: 'Favorite ' + i, status: i === 2 ? 'draft' : 'active', rentalEnabled: true, photos: [], rentalPrices: { studio: 300 } })));
  const [one, two, draft] = productIds.map(String);
  const app = express(); app.use(express.json());
  const wrap = fn => (req, res, next) => Promise.resolve(fn(req, res)).catch(next);
  app.get('/favorites', authenticate, wrap(favorites.read));
  app.post('/favorites', authenticate, wrap(favorites.add));
  app.delete('/favorites/:productId', authenticate, wrap(favorites.remove));
  app.use((error, req, res, next) => res.status(error.status || 500).json({ message: error.message }));
  server = await new Promise(resolve => { const listener = app.listen(0, '127.0.0.1', () => resolve(listener)); });
  const base = 'http://127.0.0.1:' + server.address().port + '/favorites';
  const request = async (method, token, body, suffix = '') => {
    const response = await fetch(base + suffix, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: 'Bearer ' + token } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: response.status, body: await response.json() };
  };
  assert.equal((await request('GET')).status, 401);
  assert.equal((await request('POST', tokenA, { ids: ['bad'] })).status, 400);
  assert.equal((await request('POST', tokenA, { ids: [one], userId: userB.id })).status, 400);
  await Promise.all([request('POST', tokenA, { ids: [one] }), request('POST', tokenA, { ids: [two, one, draft] })]);
  const saved = await request('GET', tokenA); assert.equal(saved.status, 200); assert.deepEqual(saved.body.ids.sort(), [one, two].sort());
  assert.deepEqual((await request('GET', tokenB)).body.ids, []);
  assert.deepEqual((await request('POST', tokenB, { ids: [one] })).body.ids, [one]);
  assert.deepEqual((await request('DELETE', tokenA, null, '/' + one)).body.ids, [two]);
  assert.deepEqual((await request('DELETE', tokenA, null, '/' + one)).body.ids, [two]);
  const query = parseCatalogueQuery({ ids: [one, draft].join(','), page: '1', limit: '24', sort: 'name' });
  const catalogue = await publicCatalogueService.list(query);
  assert.deepEqual(catalogue.items.map(item => item.id), [one]);
  assert.throws(() => parseCatalogueQuery({ ids: 'bad' }));
  assert.throws(() => parseCatalogueQuery({ ids: Array(101).fill(one).join(',') }));
  const full = Array.from({ length: 100 }, () => new mongoose.Types.ObjectId());
  await User.updateOne({ _id: userA._id }, { $set: { favorites: full } });
  assert.equal((await request('POST', tokenA, { ids: [one] })).status, 409);
  assert.equal((await User.findById(userA.id)).favorites.length, 100);
  console.log('PASS: authenticated isolation, atomic guest merge, shared product, idempotent removal, inactive product exclusion, bounded inputs and list capacity');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  if (server) await new Promise(resolve => server.close(resolve));
  await mongoose.disconnect();
  if (child && child.exitCode === null) { const stopped = new Promise(resolve => child.once('exit', resolve)); child.kill('SIGTERM'); await stopped; }
  if (directory) rmSync(directory, { recursive: true, force: true });
  clearTimeout(watchdog);
  console.log('CLEANUP: disposable database removed');
});
